// ---------------------------------------------------------------- field helpers

const dim = (id: string, label: string, description: string, extra: Partial<DatasetField> = {}): DatasetField => ({
  id,
  label,
  kind: "dimension",
  dataType: "string",
  description,
  groupable: true,
  unit: "text",
  ...extra,
})

const ident = (id: string, label: string, description: string, extra: Partial<DatasetField> = {}): DatasetField => ({
  id,
  label,
  kind: "dimension",
  dataType: "string",
  description,
  identifier: true,
  groupable: false,
  unit: "text",
  ...extra,
})

const meas = (id: string, label: string, description: string, metricId: string, unit: Unit): DatasetField => ({
  id,
  label,
  kind: "measure",
  dataType: "number",
  description,
  metricId,
  unit,
})

const date = (id: string, label: string, description: string): DatasetField => ({
  id,
  label,
  kind: "date",
  dataType: "date",
  description,
  groupable: true,
  unit: "date",
})

const calc = (id: string, label: string, description: string, metricId: string, unit: Unit, rule: Pick<DatasetField, "ratio" | "difference">): DatasetField => ({
  id,
  label,
  kind: "calculated",
  dataType: "number",
  description,
  metricId,
  unit,
  ...rule,
})

