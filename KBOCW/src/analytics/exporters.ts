import { ILLUSTRATIVE_NOTE } from "@/analytics/catalog"
import { formatGroupValue, VIZ_LABELS } from "@/analytics/engine"
import { logExport } from "@/analytics/store"
import { formatByUnit, renderChartImage } from "@/analytics/chartOptions"
import type { CellValue, QueryResult, ReportDefinition, ResultColumn, User, VizType } from "@/analytics/types"

export type ExportFormat = "xlsx" | "csv" | "pdf"

export interface ExportInput {
  def: ReportDefinition
  result: QueryResult
  user: User
  vizType: VizType
  showLabels?: boolean
  stacked?: boolean
}

const UNIT_SUFFIX: Record<string, string> = { inr: " (₹)", percent: " (%)", days: " (days)" }
const header = (column: ResultColumn) => `${column.label}${UNIT_SUFFIX[column.unit] ?? ""}`

const rawCell = (column: ResultColumn, value: CellValue) => (column.kind === "dimension" ? formatGroupValue(column, value) : (value ?? ""))

export function describePeriod(result: QueryResult) {
  const year = result.appliedFilters.find((filter) => /^Financial year/i.test(filter.label))
  if (year) return year.label.replace(/^Financial year\s+(equals|is one of)\s+/i, "FY ")
  const range = result.appliedFilters.find((filter) => / from \d{4}-\d{2}-\d{2}| up to \d{4}/.test(filter.label))
  if (range) return range.label
  return "All periods in the extract (FY 2023-24 to FY 2025-26)"
}

function slug(text: string) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "report"
}

function stamp() {
  const now = new Date()
  return `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}${String(now.getDate()).padStart(2, "0")}`
}

function fileName(def: ReportDefinition, extension: string) {
  return `KBOCW-${slug(def.name)}-${stamp()}.${extension}`
}

function download(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob)
  const link = document.createElement("a")
  link.href = url
  link.download = name
  link.click()
  window.setTimeout(() => URL.revokeObjectURL(url), 1000)
}

const generatedOn = () => new Date().toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" })

function aboutRows(input: ExportInput): (string | number)[][] {
  const { def, result, user } = input
  return [
    ["Report", def.name],
    ["Description", def.description || "Not provided"],
    ["Dataset", result.datasetName],
    ["Reporting period", describePeriod(result)],
    ["Generated on", generatedOn()],
    ["Generated by", `${user.title}, ${user.department}`],
    ["Rows in this export", result.rows.length],
    ["Source system", result.sourceSystem],
    ["Last synchronization", new Date(result.lastSync).toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" })],
    ["Filters applied", result.appliedFilters.length ? "" : "None"],
    ...result.appliedFilters.map((filter): (string | number)[] => ["", filter.label]),
    ["Visualization", VIZ_LABELS[input.vizType]],
    ["Note", ILLUSTRATIVE_NOTE],
    ...result.warnings.map((warning): (string | number)[] => ["Notice", warning]),
  ]
}

function csvEscape(value: unknown) {
  const text = String(value ?? "")
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text
}

async function exportCsv(input: ExportInput) {
  const { result, def } = input
  const lines = [
    `# ${def.name}`,
    `# Illustrative data. Reporting period: ${describePeriod(result)}. Source: ${result.sourceSystem}. Generated: ${generatedOn()}.`,
    ...(result.appliedFilters.length ? [`# Filters: ${result.appliedFilters.map((filter) => filter.label).join("; ")}`] : []),
    result.columns.map((column) => csvEscape(header(column))).join(","),
    ...result.rows.map((row) => result.columns.map((column) => csvEscape(rawCell(column, row[column.id]))).join(",")),
  ]
  download(new Blob([`\ufeff${lines.join("\r\n")}`], { type: "text/csv;charset=utf-8" }), fileName(def, "csv"))
}

async function exportExcel(input: ExportInput) {
  const XLSX = await import("xlsx")
  const { result, def } = input
  const book = XLSX.utils.book_new()
  const data = [result.columns.map(header), ...result.rows.map((row) => result.columns.map((column) => rawCell(column, row[column.id])))]
  const sheet = XLSX.utils.aoa_to_sheet(data)
  sheet["!cols"] = result.columns.map((column) => ({ wch: Math.max(14, Math.min(40, header(column).length + 4)) }))
  XLSX.utils.book_append_sheet(book, sheet, "Report")
  const about = XLSX.utils.aoa_to_sheet(aboutRows(input))
  about["!cols"] = [{ wch: 24 }, { wch: 100 }]
  XLSX.utils.book_append_sheet(book, about, "About this report")
  if (result.metrics.length > 0) {
    const definitions = XLSX.utils.aoa_to_sheet([["Metric", "Calculated as", "Definition"], ...result.metrics.map((metric) => [metric.label, metric.aggregation, metric.definition])])
    definitions["!cols"] = [{ wch: 28 }, { wch: 18 }, { wch: 110 }]
    XLSX.utils.book_append_sheet(book, definitions, "Metric definitions")
  }
  const output = XLSX.write(book, { bookType: "xlsx", type: "array" }) as ArrayBuffer
  download(new Blob([output], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }), fileName(def, "xlsx"))
}

// The built-in PDF font has no rupee sign, so it is written as "Rs." in the PDF only.
const pdfSafe = (text: string) => text.replace(/\u20b9\s?/g, "Rs. ").replace("Rs. )", "Rs.)")

async function exportPdf(input: ExportInput) {
  const { jsPDF } = await import("jspdf")
  const { default: autoTable } = await import("jspdf-autotable")
  const { result, def, user } = input
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4", compress: true })
  const margin = 40
  const width = doc.internal.pageSize.getWidth()
  const ink: [number, number, number] = [28, 25, 21]
  const brass: [number, number, number] = [138, 106, 59]

  doc.setFont("helvetica", "bold")
  doc.setFontSize(18)
  doc.setTextColor(...ink)
  doc.text(pdfSafe(def.name), margin, 48, { maxWidth: width - margin * 2 })
  doc.setFont("helvetica", "normal")
  doc.setFontSize(9)
  doc.setTextColor(...brass)
  doc.text("Illustrative data. Not connected to Karnataka Government systems.", margin, 64)
  doc.setTextColor(...ink)

  const meta: [string, string][] = [
    ["Reporting period", describePeriod(result)],
    ["Generated on", generatedOn()],
    ["Generated by", `${user.title}, ${user.department}`],
    ["Data source", `${result.datasetName}. ${result.sourceSystem}`],
    ["Last synchronization", new Date(result.lastSync).toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" })],
    ["Filters applied", result.appliedFilters.length ? result.appliedFilters.map((filter) => filter.label).join("; ") : "None"],
  ]
  autoTable(doc, {
    startY: 76,
    body: meta.map(([label, value]) => [label, pdfSafe(value)]),
    theme: "plain",
    styles: { fontSize: 9, cellPadding: 2, textColor: ink },
    columnStyles: { 0: { fontStyle: "bold", cellWidth: 120, textColor: brass }, 1: { cellWidth: width - margin * 2 - 120 } },
    margin: { left: margin, right: margin },
  })

  let cursor = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14
  const chartTypes: VizType[] = ["bar", "column", "stacked", "line", "area", "pie", "donut", "combo", "scatter", "funnel", "heatmap", "map"]
  if (chartTypes.includes(input.vizType) && result.mode === "aggregate" && result.rows.length > 0) {
    try {
      const image = await renderChartImage(input.vizType, result, { showLabels: input.showLabels ?? false, stacked: input.stacked ?? false })
      if (image) {
        const imageWidth = Math.min(width - margin * 2, 640)
        const imageHeight = (imageWidth * 420) / 900
        if (cursor + imageHeight > doc.internal.pageSize.getHeight() - 50) {
          doc.addPage()
          cursor = margin
        }
        doc.addImage(image, "JPEG", margin, cursor, imageWidth, imageHeight)
        cursor += imageHeight + 12
      }
    } catch {
      // The table below still carries the figures.
    }
  }

  autoTable(doc, {
    startY: cursor,
    head: [result.columns.map((column) => pdfSafe(header(column)))],
    body: result.rows.slice(0, 500).map((row) => result.columns.map((column) => pdfSafe(column.kind === "dimension" ? formatGroupValue(column, row[column.id]) : formatByUnit(column.unit, row[column.id] ?? null)))),
    styles: { fontSize: 8, cellPadding: 3, textColor: ink },
    headStyles: { fillColor: ink, textColor: [246, 241, 232] },
    alternateRowStyles: { fillColor: [251, 249, 245] },
    columnStyles: Object.fromEntries(result.columns.map((column, index) => [index, { halign: column.kind === "measure" ? "right" : "left" }])),
    margin: { left: margin, right: margin },
  })
  if (result.rows.length > 500) {
    doc.setFontSize(8)
    doc.text(`The first 500 of ${result.rows.length} rows are shown. Use Excel or CSV for the full set.`, margin, (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14)
  }

  if (result.metrics.length > 0) {
    autoTable(doc, {
      startY: (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 26,
      head: [["Metric", "Calculated as", "Definition"]],
      body: result.metrics.map((metric) => [pdfSafe(metric.label), metric.aggregation, pdfSafe(metric.definition)]),
      styles: { fontSize: 8, cellPadding: 3, textColor: ink },
      headStyles: { fillColor: brass, textColor: [255, 255, 255] },
      columnStyles: { 0: { cellWidth: 120 }, 1: { cellWidth: 80 } },
      margin: { left: margin, right: margin },
    })
  }

  const pages = doc.getNumberOfPages()
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page)
    doc.setFontSize(8)
    doc.setTextColor(111, 103, 94)
    doc.text("Illustrative data. This demonstration is not connected to Karnataka Government systems.", margin, doc.internal.pageSize.getHeight() - 22)
    doc.text(`Page ${page} of ${pages}`, width - margin, doc.internal.pageSize.getHeight() - 22, { align: "right" })
  }
  doc.save(fileName(def, "pdf"))
}

export async function exportReport(format: ExportFormat, input: ExportInput) {
  if (format === "csv") await exportCsv(input)
  else if (format === "xlsx") await exportExcel(input)
  else await exportPdf(input)
  logExport(input.user, { reportId: input.def.id || null, name: input.def.name, datasetId: input.def.datasetId }, format === "xlsx" ? "Excel" : format.toUpperCase(), input.result.rows.length)
}
